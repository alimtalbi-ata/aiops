const {test,expect}=require('../../../qa/mission-control/node_modules/@playwright/test');
test.use({trace:'off',screenshot:'off',video:'off',serviceWorkers:'block'});
test('runtime ACME browser read-only navigation and viewer isolation',async({page})=>{
 const token=process.env.QA_VIEWER_TOKEN;
 if(!token&&process.env.QA_REQUIRE_VIEWER==='1') throw Error('BLOCKED: approved viewer credential required');
 test.skip(!token,'BLOCKED: approved viewer credential required');
 const origin=new URL(process.env.BASE_URL);
 if(origin.protocol!=='https:'&&!['localhost','127.0.0.1','[::1]'].includes(origin.hostname)) throw Error('Viewer requires HTTPS or loopback');
 if(!/^[!-~]{32,256}$/.test(token)) throw Error('Invalid viewer format');
 const check=expect.configure({timeout:7000});
 const writes=[];
 let phase='SETUP';
 const mark=name=>{phase=name;console.log('QA_PHASE '+name);};
 page.setDefaultTimeout(7000);page.setDefaultNavigationTimeout(10000);
 test.setTimeout(120000);
 await page.route('**/*',async route=>{
  const req=route.request();
  if(!['GET','HEAD','OPTIONS'].includes(req.method())){writes.push(req.method());return route.abort();}
  if(new URL(req.url()).origin!==origin.origin)return route.abort();
  return route.continue();
 });
 try{
  mark('NAVIGATE');
  await page.goto(process.env.UI_PATH||'/mission-control');
  mark('SHELL');
  const nav=page.getByRole('navigation',{name:'Navigation'});
  await check(nav).toBeVisible();
  const go=async name=>{await nav.getByRole('button',{name,exact:true}).click();await check(page.getByRole('heading',{level:1,name,exact:true})).toBeVisible();};
  mark('MODE_SELECTOR');
  const mode=page.locator('select:has(option[value="demo"]):has(option[value="operational"])');
  await check(mode).toHaveCount(1);
  await check(mode).toHaveValue('operational');
  mark('DEMO_MODE');
  await mode.selectOption('demo');
  await check(mode).toHaveValue('demo');
  mark('VIEWER_FORM');
  await page.getByText('Accès viewer / DEMO',{exact:true}).click();
  await page.getByLabel('Viewer',{exact:true}).fill(token);
  mark('VIEWER_RESPONSES');
  const acme=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/mission-data/acme'&&r.status()===200,{timeout:15000});
  const journey=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/mission-actions/journey'&&r.status()===200,{timeout:15000});
  await page.getByRole('button',{name:'Appliquer en mémoire'}).click();
  const [ar,jr]=await Promise.all([acme,journey]);
  mark('SOURCE_BINDING');
  const a=(await ar.json()).data;const j=await jr.json();
  expect(a.source_sha256===j.source_sha256&&j.runtime_attested===false&&j.live_remediation_authorized===false).toBe(true);
  mark('SYNTHETIC_BANNER');
  await check(page.getByText(/DONNÉES SYNTHÉTIQUES/)).toBeVisible();
  mark('INCIDENTS');await go('Incidents');await check(page.getByText(j.incident_id,{exact:true})).toBeVisible();
  mark('TWIN');await go('Digital Twin');const graph=page.locator('svg[aria-label="Topologie des dépendances"]');await check(graph).toBeVisible();
  mark('TWIN_KEYBOARD');await graph.getByRole('button').first().focus();await page.keyboard.press('Enter');await check(page.locator('aside.ux-inspector')).toBeVisible();await page.keyboard.press('Escape');await check(page.locator('aside.ux-inspector')).toHaveCount(0);
  mark('INTELLIGENCE');await go('Intelligence');await check(page.getByRole('heading',{name:'Analyste',exact:true})).toBeVisible();await check(page.getByRole('heading',{name:'Critic',exact:true})).toBeVisible();
  mark('AUTOMATION');await go('Automatisation');await check(page.getByRole('button',{name:'Simuler (sans action réelle)'})).toBeDisabled();
  mark('EVIDENCE');await go('Evidence');await check(page.getByRole('heading',{name:'Checkpoints synthétiques'})).toBeVisible();await check(page.getByText(/MISSING/).first()).toBeVisible();
  mark('ITSM');await go('ITSM');await check(page.getByRole('link',{name:'Ouvrir ITSM'})).toHaveAttribute('href','/itsm');
  mark('OPERATIONAL_RETURN');
  await mode.selectOption('operational');await check(mode).toHaveValue('operational');await go('Incidents');await check(page.getByText(/Autorité acteur \/ tenant non qualifiée/)).toBeVisible();await check(page.getByText(j.incident_id,{exact:true})).toHaveCount(0);
  mark('WRITE_GUARD');
  expect(writes).toEqual([]);
 }catch{throw Error('Authenticated browser qualification failed at '+phase+'; reproduce privately without publishing credentials or payloads');}
});